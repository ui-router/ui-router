#!/usr/bin/env node

import { readFileSync, writeFileSync } from "node:fs";
import path from "node:path";
import process from "node:process";
import { fileURLToPath } from "node:url";

import {
  contractPath,
  repository,
  validateCiGates,
  workflowPath,
} from "./ci-gates-lib.mjs";

const displayNames = {
  contracts: "Contracts, install, and policy",
  source: "Source-linked quality and tests",
  packages: "Production packages and consumers",
  browser: "Workspace browser E2E",
  docs: "Documentation waiver gate",
};
function linesForFailurePaths(paths, indent) {
  return paths.map((entry) => `${" ".repeat(indent)}${entry}`).join("\n");
}
function commonHeader(contract, job, extra = []) {
  return [
    `  ${job.id}:`,
    `    name: ${displayNames[job.id]}`,
    ...extra,
    `    runs-on: ${contract.workflow.runner}`,
    `    container:`,
    `      image: ${contract.runtime.ciImage}`,
    `    timeout-minutes: ${job.timeoutMinutes}`,
  ];
}
function commonSteps(contract, job, gateArgument = job.id) {
  const actions = contract.actions;
  return [
    `    steps:`,
    `      - name: Check out exact revision`,
    `        uses: actions/checkout@${actions.checkout.sha} # ${actions.checkout.version}`,
    `        with:`,
    `          fetch-depth: 0`,
    `      - name: Trust checked-out worktree`,
    `        run: git config --global --add safe.directory "$GITHUB_WORKSPACE"`,
    `      - name: Install pinned Node`,
    `        uses: actions/setup-node@${actions.setupNode.sha} # ${actions.setupNode.version}`,
    `        with:`,
    `          node-version: ${contract.runtime.node}`,
    `          check-latest: false`,
    `      - name: Install pinned npm`,
    `        run: ${contract.runtime.npmInstallCommand.join(" ")}`,
    `      - name: Bootstrap pinned registry tarballs`,
    `        run: ${contract.runtime.npmRegistryBootstrapCommand.join(" ")}`,
    `      - name: Run ${gateArgument} gate`,
    `        run: node tools/run-ci-gate.mjs --job ${gateArgument}`,
  ];
}
function failureStep(contract, id, paths) {
  return [
    `      - name: Upload compact ${id} failure evidence`,
    `        if: failure()`,
    `        uses: actions/upload-artifact@${contract.actions.uploadArtifact.sha} # ${contract.actions.uploadArtifact.version}`,
    `        with:`,
    `          name: ci-failure-${id}-\${{ github.run_id }}-\${{ github.run_attempt }}`,
    `          path: |`,
    linesForFailurePaths(paths, 12),
    `          if-no-files-found: ignore`,
    `          include-hidden-files: true`,
    `          retention-days: ${contract.workflow.artifactRetentionDays}`,
  ];
}
export function renderWorkflow(contract) {
  const output = [
    `# Generated by tools/render-ci-workflow.mjs from migration/ci-gates.json.`,
    `# Do not edit this file directly.`,
    `name: ${contract.workflow.name}`,
    ``,
    `on:`,
    `  pull_request:`,
    `  push:`,
    `    branches:`,
    ...contract.workflow.triggers.pushBranches.map(
      (branch) => `      - ${branch}`
    ),
    ``,
    `permissions:`,
    `  contents: ${contract.workflow.permissions.contents}`,
    ``,
    `concurrency:`,
    `  group: ${contract.workflow.concurrency.group}`,
    `  cancel-in-progress: ${contract.workflow.concurrency.cancelInProgress}`,
    ``,
    `env:`,
    `  CI_RUNTIME_IMAGE_DIGEST: ${contract.runtime.ciImageDigest}`,
    ...Object.entries(contract.runtime.environment).map(
      ([key, value]) => `  ${key}: ${JSON.stringify(value)}`
    ),
    ``,
    `jobs:`,
  ];
  for (const job of contract.jobs) {
    output.push(...commonHeader(contract, job), ...commonSteps(contract, job));
    if (job.id === "packages") {
      output.push(
        `      - name: Upload content-addressed package artifacts`,
        `        uses: actions/upload-artifact@${contract.actions.uploadArtifact.sha} # ${contract.actions.uploadArtifact.version}`,
        `        with:`,
        `          name: ${contract.workflow.packageArtifactName}`,
        `          path: ${contract.artifacts.packages.directory}/`,
        `          if-no-files-found: error`,
        `          compression-level: ${contract.artifacts.packages.compressionLevel}`,
        `          include-hidden-files: ${contract.artifacts.packages.includeHiddenFiles}`,
        `          retention-days: ${contract.artifacts.packages.retentionDays}`
      );
    }
    output.push(...failureStep(contract, job.id, job.failurePaths));
  }

  output.push(
    `  integration:`,
    `    name: Isolated integration (\${{ matrix.shard }})`,
    `    needs:`,
    ...contract.integration.needs.map((need) => `      - ${need}`),
    `    runs-on: ${contract.workflow.runner}`,
    `    container:`,
    `      image: ${contract.runtime.ciImage}`,
    `    timeout-minutes: 120`,
    `    strategy:`,
    `      fail-fast: ${contract.integration.failFast}`,
    `      matrix:`,
    `        shard:`,
    ...contract.integration.shards.map((shard) => `          - ${shard.id}`),
    `    steps:`,
    `      - name: Check out exact revision`,
    `        uses: actions/checkout@${contract.actions.checkout.sha} # ${contract.actions.checkout.version}`,
    `        with:`,
    `          fetch-depth: 0`,
    `      - name: Trust checked-out worktree`,
    `        run: git config --global --add safe.directory "$GITHUB_WORKSPACE"`,
    `      - name: Install pinned Node`,
    `        uses: actions/setup-node@${contract.actions.setupNode.sha} # ${contract.actions.setupNode.version}`,
    `        with:`,
    `          node-version: ${contract.runtime.node}`,
    `          check-latest: false`,
    `      - name: Install pinned npm`,
    `        run: ${contract.runtime.npmInstallCommand.join(" ")}`,
    `      - name: Bootstrap pinned registry tarballs`,
    `        run: ${contract.runtime.npmRegistryBootstrapCommand.join(" ")}`,
    `      - name: Download producer artifacts`,
    `        uses: actions/download-artifact@${contract.actions.downloadArtifact.sha} # ${contract.actions.downloadArtifact.version}`,
    `        with:`,
    `          name: ${contract.workflow.packageArtifactName}`,
    `          path: ${contract.integration.inputDirectory}`,
    `      - name: Run isolated integration shard`,
    `        run: node tools/run-ci-gate.mjs --job integration --shard \${{ matrix.shard }}`,
    ...failureStep(
      contract,
      `integration-\${{ matrix.shard }}`,
      contract.integration.failurePaths.map((entry) =>
        entry.replaceAll("${shard}", "${{ matrix.shard }}")
      )
    )
  );

  output.push(
    `  required:`,
    `    name: Required`,
    `    if: always()`,
    `    needs:`,
    ...contract.aggregate.needs.map((need) => `      - ${need}`),
    `    runs-on: ${contract.workflow.runner}`,
    `    steps:`,
    `      - name: Require every CI gate`,
    `        shell: bash`,
    `        run: |`,
    `          set -euo pipefail`,
    ...contract.aggregate.needs.map(
      (need) =>
        `          test "\${{ needs.${need}.result }}" = "${contract.aggregate.requireResult}" || { echo "${need}: \${{ needs.${need}.result }}" >&2; exit 1; }`
    )
  );
  return `${output.join("\n")}\n`;
}

function argument(name) {
  const index = process.argv.indexOf(name);
  return index === -1 ? null : process.argv[index + 1];
}
if (process.argv[1] === fileURLToPath(import.meta.url)) {
  const unexpected = process.argv.slice(2).filter((argument, index, all) => {
    if (argument === "--write") return false;
    if (argument === "--contract" && all[index + 1]) return false;
    if (index > 0 && all[index - 1] === "--contract") return false;
    return true;
  });
  if (unexpected.length)
    throw new Error(`unknown arguments: ${unexpected.join(" ")}`);
  const source = argument("--contract") ?? path.join(repository, contractPath);
  const contract = JSON.parse(readFileSync(source, "utf8"));
  const rendered = renderWorkflow(contract);
  const target = path.join(repository, workflowPath);
  if (process.argv.includes("--write")) writeFileSync(target, rendered);
  else if (readFileSync(target, "utf8") !== rendered)
    throw new Error(
      "CI_WORKFLOW_RENDER_FAILED: workflow differs; run render-ci-workflow.mjs --write"
    );
  await validateCiGates({ contract: source });
  console.log(`CI_WORKFLOW_OK path=${workflowPath}`);
}
